// src/lib/spec.js
//
// This project's OpenAPI document: the generator script and the contract test
// both build it from here, so "what gets written" and "what gets checked" can
// never be two different things.

const path = require('node:path');
const YAML = require('yaml');

// Importing the app registers every router, which populates the route registry.
require('../app');

const { buildSpec } = require('./openapi');
const { registry } = require('./apiRouter');
const { namedSchemas } = require('../schemas');
const pkg = require('../../package.json');

const SPEC_PATH = path.join(__dirname, '..', '..', 'docs', 'openapi.yaml');
const HEADER = '# Generated by bin/generate-openapi.js — do not edit by hand.\n';

function buildProjectSpec() {
  return buildSpec({
    info: {
      title: pkg.description || pkg.name,
      version: pkg.version,
      ...(pkg.license && { license: { name: pkg.license } }),
    },
    servers: [{ url: '/', description: 'This server' }],
    // Ordering here controls section ordering in the rendered reference.
    tags: [{ name: 'Users', description: 'User accounts.' }],
    securitySchemes: {
      bearerAuth: { type: 'http', scheme: 'bearer', description: 'API key issued to a client.' },
    },
    security: [{ bearerAuth: [] }],
    namedSchemas,
    routes: registry,
  });
}

function toYaml(spec) {
  return HEADER + YAML.stringify(spec, { lineWidth: 100 });
}

module.exports = { buildProjectSpec, toYaml, SPEC_PATH, registry };
